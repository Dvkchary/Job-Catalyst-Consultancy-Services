import uuid
from typing import Any, Dict, Generic, List, Optional, Type, TypeVar, Union
from sqlalchemy import select, update, and_, desc, asc, func
from sqlalchemy.ext.asyncio import AsyncSession
from app.db.base_class import Base
from app.utils.datetime_utils import get_utc_now

# Type variables to enable subclass-specific generic compilation
ModelType = TypeVar("ModelType", bound=Base)


class BaseRepository(Generic[ModelType]):
    """
    Enterprise Generic Repository providing a unified, type-safe abstraction over 
    async database CRUD, sorting, filtering, and pagination operations.
    """

    def __init__(self, model: Type[ModelType], db: AsyncSession) -> None:
        """
        Instantiates the repository bound to a specific model class and session instance.
        """
        self.model = model
        self.db = db

    async def get(self, id: uuid.UUID) -> Optional[ModelType]:
        """
        Retrieves an active (non-soft-deleted) record by its unique primary key.
        """
        query = select(self.model).where(
            and_(
                self.model.id == id,
                # Avoid returning soft-deleted elements by default
                self.model.deleted_at.is_(None) if hasattr(self.model, "deleted_at") else True
            )
        )
        result = await self.db.execute(query)
        return result.scalar_or_none()

    async def get_raw(self, id: uuid.UUID) -> Optional[ModelType]:
        """
        Retrieves a record by its primary key, regardless of whether it is soft-deleted.
        """
        query = select(self.model).where(self.model.id == id)
        result = await self.db.execute(query)
        return result.scalar_or_none()

    async def get_multi(
        self,
        *,
        skip: int = 0,
        limit: int = 100,
        filters: Optional[Dict[str, Any]] = None,
        sort_by: Optional[str] = None,
        sort_desc: bool = False,
        include_deleted: bool = False
    ) -> List[ModelType]:
        """
        Retrieves a collection of records with flexible offset pagination, 
        granular equality filtering, and column sorting.
        """
        query = select(self.model)

        # Apply soft-delete checks
        conditions = []
        if not include_deleted and hasattr(self.model, "deleted_at"):
            conditions.append(self.model.deleted_at.is_(None))

        # Apply simple property-equality filters
        if filters:
            for field, value in filters.items():
                if hasattr(self.model, field):
                    conditions.append(getattr(self.model, field) == value)

        if conditions:
            query = query.where(and_(*conditions))

        # Apply sorting logic
        if sort_by and hasattr(self.model, sort_by):
            sort_attr = getattr(self.model, sort_by)
            query = query.order_by(desc(sort_attr) if sort_desc else asc(sort_attr))
        elif hasattr(self.model, "created_at"):
            # Default fallback sort is newest created record first
            query = query.order_by(desc(getattr(self.model, "created_at")))

        # Apply slice offset pagination limits
        query = query.offset(skip).limit(limit)

        result = await self.db.execute(query)
        return list(result.scalars().all())

    async def count(
        self,
        filters: Optional[Dict[str, Any]] = None,
        include_deleted: bool = False
    ) -> int:
        """
        Calculates the aggregate count of active records matching standard filter conditions.
        """
        query = select(func.count()).select_from(self.model)
        conditions = []
        
        if not include_deleted and hasattr(self.model, "deleted_at"):
            conditions.append(self.model.deleted_at.is_(None))
            
        if filters:
            for field, value in filters.items():
                if hasattr(self.model, field):
                    conditions.append(getattr(self.model, field) == value)
                    
        if conditions:
            query = query.where(and_(*conditions))
            
        result = await self.db.execute(query)
        return result.scalar() or 0

    async def create(self, obj_in: Dict[str, Any], creator_id: Optional[str] = None) -> ModelType:
        """
        Inserts and persists a new declarative record instance.
        """
        # Inject standard audit ownership tracker attributes
        if creator_id:
            if hasattr(self.model, "created_by"):
                obj_in["created_by"] = creator_id
            if hasattr(self.model, "updated_by"):
                obj_in["updated_by"] = creator_id

        db_obj = self.model(**obj_in)
        self.db.add(db_obj)
        await self.db.flush()  # Populates autogenerated ID, timestamps, and default values
        return db_obj

    async def update(
        self,
        *,
        db_obj: ModelType,
        obj_in: Union[Dict[str, Any], Any],
        updater_id: Optional[str] = None
    ) -> ModelType:
        """
        Mutates fields on an existing record instance.
        Handles both payload dictionary mappings or raw schema interfaces.
        """
        obj_data = obj_in if isinstance(obj_in, dict) else obj_in.model_dump(exclude_unset=True)
        
        # Inject updated_by audit ownership details
        if updater_id and hasattr(self.model, "updated_by"):
            obj_data["updated_by"] = updater_id

        # Loop through attributes and apply updates
        for field in obj_data:
            if hasattr(db_obj, field):
                setattr(db_obj, field, obj_data[field])

        # Touch updated_at automatically
        if hasattr(db_obj, "updated_at") and hasattr(db_obj, "get_utc_now"):
            setattr(db_obj, "updated_at", get_utc_now())

        self.db.add(db_obj)
        await self.db.flush()
        return db_obj

    async def delete(self, id: uuid.UUID, soft: bool = True, initiator: Optional[str] = None) -> bool:
        """
        Removes a record from active visibility pools.
        If soft=True (default), marks deleted_at timestamp. Otherwise, runs a hard SQL DELETE.
        """
        db_obj = await self.get_raw(id)
        if not db_obj:
            return False

        if soft and hasattr(db_obj, "soft_delete"):
            db_obj.soft_delete(initiator=initiator)
            self.db.add(db_obj)
            await self.db.flush()
            return True
        else:
            await self.db.delete(db_obj)
            await self.db.flush()
            return True

    async def restore(self, id: uuid.UUID) -> bool:
        """
        Restores a previously soft-deleted record back to active status.
        """
        db_obj = await self.get_raw(id)
        if not db_obj or not hasattr(db_obj, "restore"):
            return False
            
        db_obj.restore()
        self.db.add(db_obj)
        await self.db.flush()
        return True
